#!/usr/bin/env python3
"""v228 dependency guard: replaces v227's `verify-inherited.py` ("no non-app package may change").

v227 proved the *whole* non-app inventory unchanged.  v228 must change exactly four distributions
(filelock, fonttools, oauthlib: version change; plutoprint: new) and nothing else, so this guard:

  before  PyPI inventory of the app venv == expected v227 map (242), editable apps == the 13 reviewed app names,
          git pins == gunicorn/pypika commits.  Records a per-distribution digest of the *on-disk bytes* of every
          RECORD-listed file (state file; refuses to overwrite) so "unchanged" means unchanged bytes, not only
          unchanged version strings.
  after   inventory == expected v228 map (243); diff(before, after) == the reviewed delta exactly;
          every non-delta distribution has the identical version + byte digest; every delta distribution
          is a faithful install of the hash-verified wheel (see below); nothing of the replaced versions remains;
          no stray *.dist-info / *.egg-info directory.
  trust   (both phases, unchanged from v227) lock verification for both interpreters, pip/certifi CA alignment,
          system CA distrust.

Delta-wheel faithfulness (`delta-wheel-files.json`, generated by build-delta-artifacts.py from the verified
wheels): the installed RECORD file set must equal the wheel members (+ INSTALLER, REQUESTED, RECORD, uv_cache.json),
every wheel member must exist on disk with the wheel's sha256, console scripts / data files outside site-packages
must be exactly the expected set (script bodies embed the interpreter path so only RECORD consistency is checked),
and no direct_url.json may exist (it would mean install from a URL/path instead of the hashed requirement).

Stdlib only; run with `env/bin/python -I -B`.  Exit code != 0 / exception on any violation.
"""
import argparse
import base64
import csv
import hashlib
import importlib.metadata as metadata
import io
import json
import re
import ssl
import subprocess
import sys
from pathlib import Path, PurePosixPath

HERE = Path(__file__).resolve().parent
BENCH = Path("/home/frappe/frappe-bench")
ALLOWED_DISTINFO_EXTRAS = {"INSTALLER", "REQUESTED", "RECORD", "uv_cache.json"}
EXPECTED_CERTIFI_SHA = "2ef52ad56b4803e264045c915e55c236cbfa045b84b81efefc218a19eb44bd2b"  # certifi 2026.10.23 (unchanged in v228)
REMOVED_ROOTS = {"bc4d809b15189d78db3e1d8cf4f9726a795da1643ca5f1358e1ddb0edc0d7eb3",
                 "125609aa301da0a249b97a8239cb6a34216f44dcac9f3954b14292f2e8c8608f",
                 "86a1ecba089c4a8d3bbe2734c612ba341d813e043cf9e8a862cd5c57a36bbe6b"}


class GuardError(RuntimeError):
    pass


def need(ok, message):
    if not ok:
        raise GuardError(message)


def canon(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def record_rows(dist):
    text = dist.read_text("RECORD")
    need(text is not None, "Missing RECORD: " + str(dist.metadata["Name"]))
    rows = []
    for row in csv.reader(io.StringIO(text)):
        if row:
            rows.append((row[0], row[1] if len(row) > 1 else "", row[2] if len(row) > 2 else ""))
    return rows


def resolved(dist, rel):
    # RECORD paths are relative to the directory holding the dist-info (site-packages); "../../../bin/x" stays inside the venv.
    return Path(str(dist.locate_file(rel)))


def classify(paths=None):
    """-> (pypi{name: (version, dist)}, editable{name}, git{name: commit}); duplicates and unknown direct URLs fail."""
    pypi, apps, git, seen = {}, set(), {}, set()
    for dist in metadata.distributions(path=paths) if paths else metadata.distributions():
        need(dist.metadata.get("Name"), "Distribution metadata without a name: " + str(getattr(dist, "_path", "?")))
        name = canon(dist.metadata.get("Name"))
        need(name not in seen, "Duplicate installed distribution: " + name)
        seen.add(name)
        raw = dist.read_text("direct_url.json")
        if not raw:
            pypi[name] = (dist.version, dist)
            continue
        direct = json.loads(raw)
        if direct == {"url": "file:///home/frappe/frappe-bench/apps/" + name.replace("-", "_"), "dir_info": {"editable": True}}:
            apps.add(name)
        elif direct.get("url") == "https://github.com/frappe/" + name and direct.get("vcs_info", {}).get("vcs") == "git":
            git[name] = direct["vcs_info"]["commit_id"]
        else:
            raise GuardError("Unexpected direct distribution: " + name)
    return pypi, apps, git


def tree_digest(dist):
    """sha256 over `path:filehash` of the bytes actually on disk for every RECORD-listed file (RECORD itself and .pyc excluded)."""
    lines = []
    for rel, _hash, _size in record_rows(dist):
        if rel.endswith(".pyc") or PurePosixPath(rel).name == "RECORD":
            continue
        path = resolved(dist, rel)
        lines.append(rel + ":" + (sha256_file(path) if path.is_file() else "MISSING"))
    return hashlib.sha256("\n".join(sorted(lines)).encode()).hexdigest()


def snapshot(pypi):
    return {name: {"version": ver, "tree": tree_digest(dist)} for name, (ver, dist) in sorted(pypi.items())}


def diff_versions(before, after):
    return ({n: after[n] for n in after if n not in before},
            {n: {"from": before[n], "to": after[n]} for n in after if n in before and before[n] != after[n]},
            sorted(n for n in before if n not in after))


def expected_files(wheel_members, name):
    """Split wheel members into site-packages files and files installed outside it."""
    inside, outside = {}, {}
    for member, digest in wheel_members.items():
        if member.endswith(".dist-info/RECORD"):
            continue
        m = re.fullmatch(r"[^/]+\.data/data/(.+)", member)
        if m:
            outside["../../../" + m[1]] = digest
        else:
            need(".data/" not in member, "Unsupported wheel data scheme member: " + member)
            inside[member] = digest
    return inside, outside


def console_scripts(dist_text):
    names, active = [], False
    for line in (dist_text or "").splitlines():
        line = line.strip()
        if line.startswith("["):
            active = line == "[console_scripts]"
        elif active and "=" in line:
            names.append(line.split("=", 1)[0].strip())
    return names


def verify_delta_install(name, version, dist, wheel_record):
    need(dist.version == version, f"{name}: installed {dist.version}, expected {version}")
    need(dist.read_text("direct_url.json") is None, f"{name}: installed from a direct URL/path instead of the hashed requirement")
    inside, outside = expected_files(wheel_record["files"], name)
    installed_inside, installed_outside = {}, {}
    distinfo = None
    for rel, hashed, _size in record_rows(dist):
        if rel.endswith(".pyc"):
            continue
        parts = PurePosixPath(rel).parts
        if parts[0] == "..":
            installed_outside[rel] = hashed
            continue
        installed_inside[rel] = hashed
        if parts[0].endswith(".dist-info"):
            distinfo = parts[0]
    need(distinfo is not None, f"{name}: no dist-info in RECORD")
    allowed_extra = {f"{distinfo}/{x}" for x in ALLOWED_DISTINFO_EXTRAS}
    need(set(installed_inside) - allowed_extra == set(inside), f"{name}: installed file set differs from the verified wheel: "
         f"extra={sorted(set(installed_inside) - allowed_extra - set(inside))[:5]} missing={sorted(set(inside) - set(installed_inside))[:5]}")
    for rel, digest in inside.items():
        path = resolved(dist, rel)
        need(path.is_file() and not path.is_symlink(), f"{name}: missing/symlinked file {rel}")
        need(sha256_file(path) == digest, f"{name}: file differs from the hashed wheel: {rel}")
    # files outside site-packages: console scripts + data files; scripts embed the interpreter path => RECORD-consistency only
    scripts = {"../../../bin/" + s for s in console_scripts(dist.read_text("entry_points.txt"))}
    need(set(installed_outside) == scripts | set(outside), f"{name}: unexpected files outside site-packages: {sorted(set(installed_outside) ^ (scripts | set(outside)))[:5]}")
    for rel, hashed in installed_outside.items():
        path = resolved(dist, rel)
        need(path.is_file() and not path.is_symlink(), f"{name}: missing script/data {rel}")
        if rel in outside:
            need(sha256_file(path) == outside[rel], f"{name}: data file differs from the hashed wheel: {rel}")
        else:
            algo, _, b64 = hashed.partition("=")
            digest = base64.urlsafe_b64encode(hashlib.new(algo, path.read_bytes()).digest()).rstrip(b"=").decode()
            need(algo == "sha256" and digest == b64, f"{name}: script differs from its RECORD entry: {rel}")
    for rel, hashed, _size in record_rows(dist):  # uv_cache.json: bookkeeping only, must be tiny JSON
        if PurePosixPath(rel).name == "uv_cache.json":
            path = resolved(dist, rel)
            need(path.stat().st_size < 16384 and isinstance(json.loads(path.read_text()), dict), f"{name}: unexpected uv_cache.json")


def no_stray_metadata(paths, expected_dist_dirs):
    roots = {Path(p) for p in paths} if paths else {Path(p) for p in sys.path if p.endswith("site-packages")}
    found = set()
    for root in roots:
        if root.is_dir():
            found |= {c.name for c in root.iterdir() if c.is_dir() and c.name.endswith((".dist-info", ".egg-info"))}
    need(found == expected_dist_dirs, f"Stray or missing metadata directories: {sorted(found ^ expected_dist_dirs)[:8]}")


def phase_before(spec, state, paths=None):
    pypi, apps, git = classify(paths)
    need({n: v for n, (v, _d) in pypi.items()} == spec["before"], "v227 baseline inventory differs from expected-runtime-inventory.json (before)")
    need(apps == set(spec["editable_apps"]) and git == spec["git"], "Editable app / git pin inventory differs from the reviewed baseline")
    if state.exists():
        raise GuardError("Preserve prior dependency state: " + str(state))
    snap = snapshot(pypi)
    changed = set(spec["delta"]["changed"])
    old_files = {n: sorted(r for r, _h, _s in record_rows(pypi[n][1]) if not r.endswith(".pyc")) for n in changed}
    state.write_text(json.dumps({"snapshot": snap, "old_files": old_files}, sort_keys=True) + "\n")
    return {"phase": "before", "distributions": len(pypi)}


def phase_after(spec, state, wheel_files, paths=None):
    pypi, apps, git = classify(paths)
    saved = json.loads(state.read_text())
    before = {n: v["version"] for n, v in saved["snapshot"].items()}
    after = {n: v for n, (v, _d) in pypi.items()}
    need(after == spec["after"], "Post-upgrade inventory differs from expected-runtime-inventory.json (after)")
    need(before == spec["before"], "Recorded baseline differs from the reviewed baseline")
    need(apps == set(spec["editable_apps"]) and git == spec["git"], "Editable app / git pin inventory changed")
    added, changed, removed = diff_versions(before, after)
    need((added, changed, removed) == (spec["delta"]["added"], spec["delta"]["changed"], spec["delta"]["removed"]),
         f"Observed delta is not the reviewed delta: added={added} changed={changed} removed={removed}")
    delta = set(added) | set(changed)
    for name, (ver, dist) in pypi.items():
        if name in delta:
            continue
        need(saved["snapshot"][name]["tree"] == tree_digest(dist), "Non-delta distribution bytes changed: " + name)
    need(set(wheel_files) == delta, "Wheel provenance covers a different distribution set than the delta")
    for name in sorted(delta):
        verify_delta_install(name, after[name], pypi[name][1], wheel_files[name])
    for name, files in saved["old_files"].items():  # nothing of the replaced version may linger
        dist = pypi[name][1]
        new = {r for r, _h, _s in record_rows(dist)}
        for rel in files:
            if rel not in new:
                need(not resolved(dist, rel).exists(), f"{name}: file of the replaced version remains: {rel}")
    no_stray_metadata(paths, {d._path.name for _v, d in pypi.values()} | _app_dirs(paths))
    return {"phase": "after", "distributions": len(pypi), "delta": {"added": added, "changed": changed}}


def _app_dirs(paths):
    out = set()
    for dist in metadata.distributions(path=paths) if paths else metadata.distributions():
        if dist.read_text("direct_url.json"):
            out.add(dist._path.name)
    return out


def phase_trust(lock_app, lock_maint, verify_lock, maintenance_python="/usr/local/bin/python"):
    """Unchanged v227 behaviour, with explicit lock paths (app venv lock = v227 lock before, v228 lock after)."""
    for interpreter, lock, maintenance in ((str(BENCH / "env/bin/python"), lock_app, False), (maintenance_python, lock_maint, True)):
        subprocess.run([interpreter, "-I", "-B", verify_lock, str(lock), *(["--maintenance"] if maintenance else [])], check=True)
        code = ("import certifi,pip._vendor.certifi,pathlib,hashlib; "
                "print(hashlib.sha256(pathlib.Path(certifi.where()).read_bytes()).hexdigest()); "
                "print(hashlib.sha256(pathlib.Path(pip._vendor.certifi.where()).read_bytes()).hexdigest())")
        hashes = subprocess.check_output([interpreter, "-I", "-B", "-c", code], text=True).splitlines()
        need(hashes == [EXPECTED_CERTIFI_SHA] * 2, "Inherited pip/certifi CA alignment changed")
    trusted = {hashlib.sha256(c).hexdigest() for c in ssl.create_default_context().get_ca_certs(binary_form=True)}
    need(len(trusted) >= 100 and not (trusted & REMOVED_ROOTS), "Inherited system CA distrust changed")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("phase", choices=("before", "after"))
    ap.add_argument("--spec", default=str(HERE / "expected-runtime-inventory.json"))
    ap.add_argument("--wheel-files", default=str(HERE / "delta-wheel-files.json"))
    ap.add_argument("--state", default=str(HERE / "dependency-before.json"))
    ap.add_argument("--path", action="append", help="site-packages directory (tests); default: interpreter's")
    ap.add_argument("--lock-before", default=str(HERE / "python-security-v227.lock"))
    ap.add_argument("--lock-after", default=str(HERE / "python-security-v228.lock"))
    ap.add_argument("--lock-maintenance", default=str(HERE / "maintenance-python-security.lock"))
    ap.add_argument("--verify-lock", default=str(HERE / "verify-python-lock.py"))
    ap.add_argument("--no-trust", action="store_true", help="skip interpreter/CA checks (tests only)")
    a = ap.parse_args(argv)
    spec = json.loads(Path(a.spec).read_text())
    state = Path(a.state)
    if a.phase == "before":
        result = phase_before(spec, state, a.path)
    else:
        result = phase_after(spec, state, json.loads(Path(a.wheel_files).read_text()), a.path)
    if not a.no_trust:
        phase_trust(a.lock_before if a.phase == "before" else a.lock_after, a.lock_maintenance, a.verify_lock)
    print(json.dumps({"pass": True, **result}, sort_keys=True))


if __name__ == "__main__":
    main()
